import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=new URL('../',import.meta.url),base=await readFile(new URL('dist/contract-review.html',root),'utf8');
const hash=x=>createHash('sha256').update(x).digest('hex');
const css=await readFile(new URL('preserved-ui.css',import.meta.url),'utf8');
const js=await readFile(new URL('preserved-ui.js',import.meta.url),'utf8');
new Function(js);
const head=base.lastIndexOf('</head>'),body=base.lastIndexOf('</body>');assert(head>0&&body>head);
const cssInsert='<style id="ux-preserved-style">\n'+css+'\n</style>\n';
const jsInsert='<script id="ux-preserved-ui">\n'+js+'\n</script>\n';
const output=base.slice(0,head)+cssInsert+base.slice(head,body)+jsInsert+base.slice(body);
assert.equal(output.replace(cssInsert,'').replace(jsInsert,''),base,'Entire original document recoverable byte-for-byte');
const scriptBodies=s=>[...s.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>hash(m[1]));
const originalScripts=scriptBodies(base),newScripts=scriptBodies(output);
assert.deepEqual(newScripts.slice(0,-1),originalScripts,'All original script/data payloads preserved');
await writeFile(new URL('review-preserved-v2.html',import.meta.url),output);
await writeFile(new URL('preservation-manifest.json',import.meta.url),JSON.stringify({source:'dist/contract-review.html',source_sha256:hash(base),prototype_sha256:hash(output),original_script_blocks:originalScripts.length,original_script_hashes:originalScripts,original_document_byte_preserved:true,added_files:['preserved-ui.css','preserved-ui.js'],source_bytes:Buffer.byteLength(base),prototype_bytes:Buffer.byteLength(output)},null,2)+'\n');
console.log(JSON.stringify({original_document_byte_preserved:true,original_script_blocks:originalScripts.length,source_sha256:hash(base),output:'prototypes/review-preserved-v2.html'}));
